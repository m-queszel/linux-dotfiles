def mime_kind(name):
    if name.startswith("inode-directory"):
        return "folder"
    for prefix, kind in (("image-", "image"), ("audio-", "audio"), ("video-", "video")):
        if name.startswith(prefix):
            return kind
    if CONFIG.search(name):
        return "config"
    if EXEC.search(name):
        return "exec"
    if ARCHIVE.search(name):
        return "package"
    if CODE.search(name):
        return "code"
    return "text"


def place_kind(name):
    if "trash" in name:
        return "trash"
    if "home" in name:
        return "home"
    if "desktop" in name:
        return "desktop"
    if "download" in name:
        return "download"
    if "folder" in name or "directory" in name or name.startswith(("user-", "stock_")):
        return "folder"
    return None


def parse(art, size):
    rows = [r.strip() for r in art.strip().splitlines()]
    assert len(rows) == size and all(len(r) == size for r in rows), f"bad {size}px sprite"
    return rows


def lighten(hex_color, amount):
    r, g, b = (int(hex_color[i : i + 2], 16) / 255 for i in (1, 3, 5))
    h, lum, s = colorsys.rgb_to_hls(r, g, b)
    r, g, b = colorsys.hls_to_rgb(h, min(1, max(0, lum + amount / 100)), s)
    return "#{:02x}{:02x}{:02x}".format(*(round(c * 255) for c in (r, g, b)))


def is_dark(hex_color):
    r, g, b = (int(hex_color[i : i + 2], 16) for i in (1, 3, 5))
    return 0.2126 * r + 0.7152 * g + 0.0722 * b < 128


def palette(c, dark):
    ink = lighten(c["primary_container"], -14) if dark else c["on_primary_container"]
    pal = {
        "o": ink,
        "e": ink,
        "c": c["error"] if dark else lighten(c["error"], 30),
        "s": lighten(c["primary"], 25),
        "H": lighten(c["primary"], 12),
        "a": c["primary"],
        "b": lighten(c["primary"], -22),
        "B": c["primary_container"],
        "w": c["on_surface"] if dark else c["surface_container_lowest"],
        "p": c["on_surface_variant"] if dark else c["surface_container_high"],
        "d": c["outline"],
        "g": c["tertiary"],
        "G": lighten(c["tertiary"], -22),
        "K": c["surface_container_high"] if dark else c["inverse_surface"],
    }
    return pal


def svg(rows, pal, shadow):
    size = len(rows)
    grid = [[pal.get(ch) for ch in row] for row in rows]
    layer = [[None] * size for _ in range(size)]
    for y in range(size - 1):
        for x in range(size - 1):
            if grid[y][x] and not grid[y + 1][x + 1]:
                layer[y + 1][x + 1] = shadow
    rects = []
    for src in (layer, grid):
        for y, row in enumerate(src):
            x = 0
            while x < size:
                col = row[x]
                if not col:
                    x += 1
                    continue
                end = x
                while end < size and row[end] == col:
                    end += 1
                rects.append(f'<rect x="{x}" y="{y}" width="{end - x}" height="1" fill="{col}"/>')
                x = end
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" '
        f'viewBox="0 0 {size} {size}" shape-rendering="crispEdges">{"".join(rects)}</svg>\n'
    )


def index_theme(name, dark):
    dirs = [f"{s}x{s}/{ctx}" for s in SPRITES for ctx in ("places", "mimetypes", "devices")]
    out = [
        "[Icon Theme]",
        f"Name={name}",
        "Comment=Pixel file icons recoloured from the wallpaper by ~/.config/pixel-icons/render.py",
        f"Inherits={'Papirus-Dark' if dark else 'Papirus-Light'},hicolor",
        f"Directories={','.join(dirs)}",
    ]
    for d in dirs:
        size = int(d.split("x")[0])
        ctx = {"places": "Places", "mimetypes": "MimeTypes", "devices": "Devices"}[d.split("/")[1]]
        scale = "Type=Fixed" if size == 16 else "Type=Scalable\nMinSize=17\nMaxSize=96"
        out += ["", f"[{d}]", f"Size={size}", f"Context={ctx}", scale]
    return "\n".join(out) + "\n"


def write_atomic(path, text):
    tmp = path.with_suffix(".tmp")
    tmp.write_text(text)
    os.replace(tmp, path)


def link(path, target):
    if path.is_symlink() and os.readlink(path) == target:
        return
    if path.exists() or path.is_symlink():
        path.unlink()
    path.symlink_to(target)


def main():
    colors = json.loads(Path(sys.argv[1]).read_text())
    dark = is_dark(colors["surface"])
    pal = palette(colors, dark)
    name = sys.argv[2] if len(sys.argv) > 2 else "PixelInk-0"
    data = Path(os.environ.get("XDG_DATA_HOME") or Path.home() / ".local/share")
    theme = data / "icons" / name
    papirus = Path("/usr/share/icons/Papirus")

    for size, sprites in SPRITES.items():
        base = theme / f"{size}x{size}"
        for ctx in ("places", "mimetypes", "devices"):
            (base / ctx).mkdir(parents=True, exist_ok=True)
        for kind, art in sprites.items():
            write_atomic(base / "mimetypes" / f"pixelink-{kind}.svg", svg(parse(art, size), pal, colors["tertiary"]))

        names = {"mimetypes": {}, "places": {}, "devices": {}}
        for n in ("inode-directory", "text-x-generic", "image-x-generic", "audio-x-generic", "video-x-generic"):
            names["mimetypes"][n] = mime_kind(n)
        for n in ("folder", "user-home", "user-desktop", "folder-download", "user-trash", "user-trash-full"):
            names["places"][n] = place_kind(n)
        names["places"]["go-home"] = "home"
        names["devices"]["drive-harddisk"] = "drive"
        names["devices"]["computer"] = "desktop"
        src = papirus / f"{size}x{size}"
        for f in (src / "mimetypes").glob("*.svg"):
            names["mimetypes"][f.stem] = mime_kind(f.stem)
        for f in (src / "places").glob("*.svg"):
            if kind := place_kind(f.stem):
                names["places"][f.stem] = kind
        for f in (src / "devices").glob("drive-*.svg"):
            names["devices"][f.stem] = "drive"
        for ctx, mapping in names.items():
            prefix = "" if ctx == "mimetypes" else "../mimetypes/"
            for icon, kind in mapping.items():
                link(base / ctx / f"{icon}.svg", f"{prefix}pixelink-{kind}.svg")

    apps = theme / "24x24" / "apps"
    apps.mkdir(parents=True, exist_ok=True)
    for kind, art in APP_SPRITES.items():
        rows = parse(art, 24)
        write_atomic(apps / f"pixelink-{kind}.svg", svg(rows, pal, colors["tertiary"]))
        for tag, col in (("a", colors["primary"]), ("b", colors["tertiary"])):
            flat = {ch: col for row in rows for ch in row if ch != "."}
            write_atomic(apps / f"pixelink-{kind}-fringe-{tag}.svg", svg(rows, flat, None))

    write_atomic(theme / "index.theme", index_theme(name, dark))
    stable = data / "icons/PixelInk"
    tmp = stable.with_suffix(".tmp")
    tmp.unlink(missing_ok=True)
    tmp.symlink_to(name)
    os.replace(tmp, stable)


if __name__ == "__main__":
    main()
